// Subresource Integrity hashes for the scripts the site loads, so every one can
// carry an `integrity` attribute (groundwork for enforcing
// `Integrity-Policy: blocked-destinations=(script)`). Three shapes:
//
//   sri("/x.js")   — committed files under public/, hashed from their bytes at
//                    build time (Node/SSG, never shipped), so the hash can't
//                    drift from what we serve.
//   pagefind*      — the Pagefind runtime + component UI, emitted by
//                    `pagefind --site dist` AFTER the Astro build, so they can't
//                    be hashed here: committed constants, guarded by
//                    scripts/check-integrity.mjs. Version-stable (no site data).
//   webmcp         — generated per-build from spec content (see src/lib/webmcp.ts),
//                    hashed from its exact generated bytes.
//
// None of these files are fingerprinted, and Cloudflare caches them for hours.
// After a deploy that changes one, a returning visitor's cached copy would no
// longer match the new hash in the HTML and the browser would block it. So each
// URL also carries a slice of its own hash (versioned(), pinned()): new bytes,
// new URL, no collision with the stale copy. The query is ignored when serving.
//
// The exception is /pagefind/pagefind.js: Pagefind's UI imports it by a fixed
// path, which is also the import-map key carrying its hash. Its bytes only move
// on a Pagefind version bump.
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

/** sha384 SRI hash (`sha384-<base64>`) of raw bytes or a UTF-8 string. */
export function sriOf(bytes: Buffer | string): string {
  return `sha384-${createHash("sha384").update(bytes).digest("base64")}`;
}

const fileCache = new Map<string, string>();

/**
 * SRI hash of a committed file under public/, addressed by its served path
 * (e.g. "/search.js" → public/search.js). Memoised across the many page renders.
 */
export function sri(servedPath: string): string {
  let value = fileCache.get(servedPath);
  if (!value) {
    value = sriOf(readFileSync(join(process.cwd(), "public", servedPath)));
    fileCache.set(servedPath, value);
  }
  return value;
}

/**
 * Cache-busting query value derived from an SRI hash: 12 base64 chars of the
 * digest, with `+` and `/` swapped for `_` so it needs no URL escaping. Mirrored
 * in public/search.js and functions/admin/stats.ts, which can't import this.
 */
export function hashVersion(integrity: string): string {
  return integrity.slice(7, 19).replace(/[^A-Za-z0-9]/g, "_");
}

/** `servedPath?v=<hash slice>` — a URL that changes whenever the bytes do. */
export function versioned(servedPath: string, integrity: string): string {
  return `${servedPath}?v=${hashVersion(integrity)}`;
}

/**
 * `{ src, integrity }` for a committed file under public/, ready to spread onto
 * a <script>: `<script {...pinned("/x.js")} crossorigin="anonymous">`.
 */
export function pinned(servedPath: string): { src: string; integrity: string } {
  const integrity = sri(servedPath);
  return { src: versioned(servedPath, integrity), integrity };
}

